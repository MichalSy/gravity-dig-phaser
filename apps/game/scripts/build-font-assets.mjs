import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const appRoot = join(__dirname, '..');
const fontsRoot = join(appRoot, 'public', 'fonts');
const generatedTsPath = join(appRoot, 'src', 'assets', 'generatedFontAssets.ts');
const manifestPath = join(fontsRoot, 'manifest.json');
const fontExtensions = new Set(['.woff2', '.woff', '.ttf', '.otf']);

const weightNames = new Map([
  ['thin', '100'],
  ['extralight', '200'],
  ['extra-light', '200'],
  ['light', '300'],
  ['regular', '400'],
  ['normal', '400'],
  ['medium', '500'],
  ['semibold', '600'],
  ['semi-bold', '600'],
  ['bold', '700'],
  ['extrabold', '800'],
  ['extra-bold', '800'],
  ['black', '900'],
]);
const weightLabels = new Map([
  ['100', 'Thin'],
  ['200', 'Extra Light'],
  ['300', 'Light'],
  ['400', 'Regular'],
  ['500', 'Medium'],
  ['600', 'Semi Bold'],
  ['700', 'Bold'],
  ['800', 'Extra Bold'],
  ['900', 'Black'],
]);
const styleNames = new Set(['italic', 'oblique']);
const subsetNames = new Set(['latin', 'latin-ext', 'cyrillic', 'greek', 'vietnamese']);

async function listFontFiles(directory) {
  let entries = [];
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error?.code === 'ENOENT') return [];
    throw error;
  }

  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listFontFiles(fullPath));
      continue;
    }
    if (!entry.isFile()) continue;
    if (entry.name === 'manifest.json') continue;
    if (!fontExtensions.has(extname(entry.name).toLowerCase())) continue;
    files.push(fullPath);
  }
  return files.sort((a, b) => a.localeCompare(b));
}

function titleCase(token) {
  return token.length === 0 ? token : `${token[0].toUpperCase()}${token.slice(1)}`;
}

function parseFont(filePath) {
  const rel = relative(fontsRoot, filePath).replaceAll('\\', '/');
  const extension = extname(rel);
  const basename = rel.slice(0, -extension.length);
  const id = basename.toLowerCase().replace(/[^a-z0-9]+/gu, '-').replace(/^-|-$/gu, '');
  const rawTokens = basename.split(/[\s_-]+/u).filter(Boolean);
  const tokens = rawTokens.map((token) => token.toLowerCase());

  let weight;
  let style;
  const familyTokens = [];
  for (let index = 0; index < rawTokens.length; index += 1) {
    const rawToken = rawTokens[index];
    const token = tokens[index];
    if (/^[1-9]00$/u.test(token)) {
      weight = token;
      continue;
    }
    if (weightNames.has(token)) {
      weight = weightNames.get(token);
      continue;
    }
    if (styleNames.has(token)) {
      style = token;
      continue;
    }
    if (subsetNames.has(token)) continue;
    familyTokens.push(rawToken);
  }

  const family = familyTokens.length > 0 ? familyTokens.map((token) => titleCase(token.toLowerCase())).join(' ') : titleCase(id);
  const suffix = [style && titleCase(style), weight ? weightLabels.get(weight) ?? weight : undefined].filter(Boolean).join(' ');
  const label = suffix ? `${family} ${suffix}` : family;

  return {
    key: id,
    family,
    label,
    path: `/fonts/${rel}`,
    ...(weight ? { weight } : {}),
    ...(style ? { style } : {}),
  };
}

function generatedTs(fonts) {
  return `import type { FontAssetDefinition } from '@gravity-dig/game-core';\n\n// Auto-generated by apps/game/scripts/build-font-assets.mjs.\n// Add font files to apps/game/public/fonts and rerun the build/dev script.\nexport const GENERATED_FONT_ASSETS = ${JSON.stringify(fonts, null, 2)} satisfies readonly FontAssetDefinition[];\n`;
}

await mkdir(fontsRoot, { recursive: true });
const fonts = (await listFontFiles(fontsRoot)).map(parseFont);
await writeFile(generatedTsPath, generatedTs(fonts));
await writeFile(manifestPath, `${JSON.stringify({ version: 1, fonts }, null, 2)}\n`);
console.log(`Built ${fonts.length} font asset(s) from public/fonts.`);
